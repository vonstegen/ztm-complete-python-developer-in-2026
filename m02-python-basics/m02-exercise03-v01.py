# Guess the output of each print statement before you click RUN!
python = "I am PYTHON"

print(python[1:4])  # ' am '
print(python[1:])  # ' am PYTHON'
print(python[:])  # 'I am PYTHON'
print(python[1:100])  # ERROR ' am PYTHON'
print(python[-1])  # 'N'
print(python[-4])  # 'H' T
print(python[:-3])  # 'I am PYTH' No H
print(python[-3:])  # 'HON'
print(python[::-1])  # 'I am PYTHO' Reverse
